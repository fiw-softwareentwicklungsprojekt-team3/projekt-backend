-- V1: Kerntabellen laut ER-Modell (E1.1)

CREATE TABLE modul(
    code VARCHAR(10) PRIMARY KEY,
    bezeichnung VARCHAR(150) NOT NULL,
    fachsemester SMALLINT NOT NULL CHECK (fachsemester BETWEEN 1 AND 6),
    art VARCHAR(2) NOT NULL CHECK (art IN ('P', 'WP')),
    bereich VARCHAR(4) NOT NULL CHECK (bereich IN ('FACH', 'AWE')),
    mit_auswahl BOOLEAN NOT NULL DEFAULT FALSE,
    lp SMALLINT NOT NULL CHECK (lp>0),
    sws_vorlesung SMALLINT NOT NULL CHECK (sws_vorlesung>=0),
    sws_uebung SMALLINT NOT NULL CHECK (sws_uebung>=0),
    niveaustufe VARCHAR(2) NOT NULL CHECK (niveaustufe IN ('1a', '1b')),
    turnus VARCHAR(5) NOT NULL CHECK (turnus IN ('WS', 'SS', 'BEIDE')),
     zaehlt_in_x1    BOOLEAN      NOT NULL DEFAULT TRUE,
    benotet         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE modul_teil (
    modul_code VARCHAR(10) NOT NULL REFERENCES modul(code),
    teil_code VARCHAR(10) NOT NULL,
    bezeichnung VARCHAR(150) NOT NULL,
    sws SMALLINT  CHECK (sws>=0),
    PRIMARY KEY (modul_code, teil_code)
);

CREATE TABLE voraussetzung (
    voraussetzung_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modul_code VARCHAR(10) NOT NULL REFERENCES modul(code),
    art VARCHAR(10) NOT NULL CHECK (art IN ('NOTWENDIG', 'EMPFOHLEN')),
    voraussetzung_code VARCHAR(10)  REFERENCES modul(code),
    min_lp SMALLINT CHECK (min_lp>=0),
    toleranz_lp SMALLINT NOT NULL DEFAULT 0 CHECK (toleranz_lp>=0),
    CONSTRAINT chk_voraussetzung_modul_oder_lp
        CHECK ((vorausgesetzt_modul_code IS NULL) <> (min_lp IS NULL)),
    CONSTRAINT chk_voraussetzung_nicht_selbst
        CHECK (vorausgesetzt_modul_code <> modul_code),
    CONSTRAINT chk_voraussetzung_toleranz
        CHECK (toleranz_lp = 0 OR (min_lp IS NOT NULL AND toleranz_lp <= min_lp))
);

CREATE UNIQUE INDEX uq_voraussetzung_modul
 ON voraussetzung(modul_code, art, vorausgesetzt_modul_code);
 WHERE vorausgesetzt_modul_code IS NOT NULL;
 CREATE UNIQUE INDEX uq_voraussetzung_lp
    ON voraussetzung(modul_code, art, min_lp)
    WHERE min_lp IS NOT NULL;

CREATE TABLE wahlangebot(
    code VARCHAR(10) PRIMARY KEY,
    bezeichnung VARCHAR(150) NOT NULL,
    gruppe VARCHAR(10) NOT NULL CHECK (gruppe IN ('WP', 'SPRACHE')),
    niveaustufe VARCHAR(2)  CHECK (niveaustufe IN ('1a', '1b')),
    sws SMALLINT  CHECK (sws>=0),
    empfohlen_modul_code  VARCHAR(10)  REFERENCES modul (code)
);

CREATE TABLE semester(
    semester_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jahr SMALLINT NOT NULL CHECK (jahr BETWEEN 2000 AND 2100),
    art VARCHAR(2) NOT NULL CHECK (art IN ('WS', 'SS')),
    CONSTRAINT uq_semester UNIQUE (jahr, art);
)
